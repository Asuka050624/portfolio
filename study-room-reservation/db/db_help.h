/********************************************************************
 * 文件名称：db_helper.h
 * 文件用途：数据库操作辅助头文件，专门声明MySQL数据库的连接/关闭函数
 *          是整个项目中所有数据库操作的基础入口，任何需要操作MySQL的功能（登录、注册、预约）都要包含此文件
 * 使用位置：db_helper.c（实现函数）、user_auth.c（登录注册）、main.c（测试）等所有操作数据库的文件中
 ********************************************************************/
#ifndef DB_HELPER_H  // 头文件保护宏：防止头文件被重复包含（C语言必加，否则编译会报错）
#define DB_HELPER_H

/************************** 引入依赖头文件 **************************
 * 作用：引入实现数据库操作需要的库函数声明
 * 1. mysql/mysql.h：MySQL官方头文件，提供连接、查询等API函数
 * 2. stdio.h：标准输入输出，用于打印日志（如连接失败提示）
 * 3. stdlib.h：标准库，用于内存分配/程序退出等基础操作
 ******************************************************************/
#include <mysql/mysql.h>
#include <stdio.h>
#include <stdlib.h>

/************************** 数据库连接配置宏 **************************
 * 作用：定义MySQL的连接信息，集中管理配置，修改此处即可适配不同的数据库环境
 * 使用场景：init_mysql_conn()函数中会调用这些宏来连接数据库
 * 注意事项：必须将DB_PWD替换为你自己的MySQL密码，其他参数默认不用改
 ********************************************************************
 * 宏说明：
 * DB_HOST：数据库主机地址，localhost表示本地数据库
 * DB_USER：MySQL用户名，默认是root
 * DB_PWD：MySQL密码，需要替换成你自己的（比如你的密码是123456，就写"123456"）
 * DB_NAME：数据库名，对应Navicat中创建的reserveStudyRoom
 * DB_PORT：MySQL端口号，默认是3306
 ******************************************************************/
#define DB_HOST "localhost"   // 数据库主机地址（本地）
#define DB_USER "root"        // MySQL登录用户名
#define DB_PWD "123456"// 替换成你自己的MySQL密码！！！
#define DB_NAME "reserveStudyRoom" // 数据库名（和Navicat中一致）
#define DB_PORT 3306          // MySQL端口号（默认3306）

/************************** 函数声明 **************************
 * 作用：声明数据库操作的工具函数，具体实现写在db_helper.c中
 * 函数调用场景：
 * 1. init_mysql_conn()：程序启动时调用，用于建立数据库连接（如登录/注册前必须先调用）
 * 2. close_mysql_conn()：程序结束时调用，用于关闭数据库连接（释放资源）
 ******************************************************************/

/**
 * 函数名称：init_mysql_conn
 * 函数功能：初始化并建立MySQL数据库连接
 * 参数说明：无
 * 返回值：成功返回MySQL连接对象（MYSQL*），失败返回NULL
 * 使用场景：登录、注册、预约等所有数据库操作前，必须先调用此函数建立连接
 * 示例：MYSQL* conn = init_mysql_conn();
 */
MYSQL* init_mysql_conn();

/**
 * 函数名称：close_mysql_conn
 * 函数功能：关闭MySQL数据库连接，释放资源
 * 参数说明：conn - 已建立的MySQL连接对象（init_mysql_conn()的返回值）
 * 返回值：无
 * 使用场景：数据库操作完成后调用（如登录/注册结束后），避免资源泄露
 * 示例：close_mysql_conn(conn);
 */
void close_mysql_conn(MYSQL* conn);

#endif // DB_HELPER_H  // 头文件保护宏的结束标记